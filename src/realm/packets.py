CMD_AUTH_LOGON_CHALLENGE: Final[int] = 0x00
CMD_AUTH_LOGON_PROOF: Final[int] = 0x01
CMD_REALM_LIST: Final[int] = 0x10


class AuthResult:
    """Realm authentication result codes."""

    WOW_SUCCESS: Final[int] = 0x00
    WOW_FAIL_BANNED: Final[int] = 0x03
    WOW_FAIL_UNKNOWN_ACCOUNT: Final[int] = 0x04
    WOW_FAIL_INCORRECT_PASSWORD: Final[int] = 0x05
    WOW_FAIL_ALREADY_ONLINE: Final[int] = 0x06
    WOW_FAIL_NO_TIME: Final[int] = 0x07
    WOW_FAIL_DB_BUSY: Final[int] = 0x08
    WOW_FAIL_VERSION_INVALID: Final[int] = 0x09
    WOW_FAIL_VERSION_UPDATE: Final[int] = 0x0A
    WOW_FAIL_INVALID_SERVER: Final[int] = 0x0B
    WOW_FAIL_SUSPENDED: Final[int] = 0x0C
    WOW_FAIL_FAIL_NOACCESS: Final[int] = 0x0D
    WOW_SUCCESS_SURVEY: Final[int] = 0x0E
    WOW_FAIL_PARENTCONTROL: Final[int] = 0x0F
    WOW_FAIL_LOCKED_ENFORCED: Final[int] = 0x10
    WOW_FAIL_TRIAL_ENDED: Final[int] = 0x11
    WOW_FAIL_USE_BATTLENET: Final[int] = 0x12
    WOW_FAIL_ANTI_INDULGENCE: Final[int] = 0x13
    WOW_FAIL_EXPIRED: Final[int] = 0x14
    WOW_FAIL_NO_GAME_ACCOUNT: Final[int] = 0x15
    WOW_FAIL_CHARGEBACK: Final[int] = 0x16
    WOW_FAIL_INTERNET_GAME_ROOM_WITHOUT_BNET: Final[int] = 0x17
    WOW_FAIL_GAME_ACCOUNT_LOCKED: Final[int] = 0x18
    WOW_FAIL_UNLOCKABLE_LOCK: Final[int] = 0x19
    WOW_FAIL_CONVERSION_REQUIRED: Final[int] = 0x20
    WOW_FAIL_DISCONNECTED: Final[int] = 0xFF

    @staticmethod
    def is_success(result: int) -> bool:
        """
        Check if the auth result indicates a successful login.

        Args:
            result: Auth result code from the server.

        Returns:
            True if the code is WOW_SUCCESS or WOW_SUCCESS_SURVEY.
        """
        return result in (AuthResult.WOW_SUCCESS, AuthResult.WOW_SUCCESS_SURVEY)

    @staticmethod
    def get_message(result: int) -> str:
        """
        Return a human-readable message for an auth error code.

        Args:
            result: Auth result code from the server.

        Returns:
            Descriptive error message or a formatted unknown code string.
        """
        messages = {
            AuthResult.WOW_SUCCESS: "Success!",
            AuthResult.WOW_SUCCESS_SURVEY: "Success!",
            AuthResult.WOW_FAIL_BANNED: "Your account has been banned!",
            AuthResult.WOW_FAIL_INCORRECT_PASSWORD: (
                "Incorrect username or password!"
            ),
            AuthResult.WOW_FAIL_UNKNOWN_ACCOUNT: (
                "Login failed. Possibly incorrect username or password."
            ),
            AuthResult.WOW_FAIL_ALREADY_ONLINE: (
                "Your account is already online."
            ),
            AuthResult.WOW_FAIL_VERSION_INVALID: (
                "Invalid realm version for this server!"
            ),
            AuthResult.WOW_FAIL_VERSION_UPDATE: (
                "Old realm version for this server!"
            ),
            AuthResult.WOW_FAIL_SUSPENDED: (
                "Your account has been suspended!"
            ),
            AuthResult.WOW_FAIL_FAIL_NOACCESS: (
                "Login failed! You do not have access to this server!"
            ),
        }
        return messages.get(
            result,
            f"Failed to login to realm server! Error code: {result:02X}",
        )


@dataclass
class RealmListEntry:
    """A single realm entry from the realm list."""

    name: str
    address: str
    realm_id: int


