"""
SHA1-based pseudo-random byte generator used for Warden RC4 key derivation.
"""

from __future__ import annotations

import hashlib


class SHA1Randx:
    """
    Continuous SHA1-based PRNG as used by WoW's Warden system.

    Derives two 20-byte halves (o1, o2) from a session key via:
      o1 = SHA1(session_key[0:half])
      o2 = SHA1(session_key[half:])

    Generates an infinite stream of bytes by repeatedly hashing
    o1 || o0 || o2, where o0 is the previous output.

    Args:
        session_key: 40-byte session key from realm auth.
    """

    def __init__(self, session_key: bytes) -> None:
        half = len(session_key) // 2
        self._o1 = hashlib.sha1(session_key[:half]).digest()
        self._o2 = hashlib.sha1(session_key[half:]).digest()
        self._o0 = b"\x00" * 20
        self._buffer = b""
        self._index = 0
        self._fill()

    def _fill(self) -> None:
        """Generate the next 20-byte block."""
        md = hashlib.sha1()
        md.update(self._o1)
        md.update(self._o0)
        md.update(self._o2)
        self._o0 = md.digest()
        self._buffer = self._o0
        self._index = 0

    def generate(self, size: int) -> bytes:
        """
        Generate *size* pseudo-random bytes.

        Args:
            size: Number of bytes to generate.

        Returns:
            Generated bytes.
        """
        result = bytearray(size)
        for i in range(size):
            if self._index >= len(self._buffer):
                self._fill()
            result[i] = self._buffer[self._index]
            self._index += 1
        return bytes(result)
